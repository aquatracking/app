import { test } from '@japa/runner'
import User from '#models/user'
import { validate, version } from 'uuid'
import testUtils from '@adonisjs/core/services/test_utils'

test.group('UUIDv7 primary keys', (group) => {
  group.each.setup(() => testUtils.db().withGlobalTransaction())

  test('a created model gets a UUIDv7 generated by the application', async ({ assert }) => {
    const user = await User.create({
      firstName: 'Ada',
      email: 'ada@example.com',
      password: 'secret-password',
    })

    assert.isTrue(validate(user.id))
    assert.equal(version(user.id), 7)
    assert.isNotNull(await User.find(user.id))
  })

  test('consecutive ids are ordered by creation time', async ({ assert }) => {
    const first = await User.create({
      firstName: 'A',
      email: 'a@example.com',
      password: 'pw-12345',
    })
    const second = await User.create({
      firstName: 'B',
      email: 'b@example.com',
      password: 'pw-12345',
    })

    assert.isBelow(first.id.localeCompare(second.id), 0)
  })

  test('an id given explicitly is kept', async ({ assert }) => {
    const id = '01936f4e-8a2b-7c3d-9e4f-5a6b7c8d9e0f'
    const user = await User.create({
      id,
      firstName: 'C',
      email: 'c@example.com',
      password: 'pw-12345',
    })

    assert.equal(user.id, id)
    assert.isNotNull(await User.find(id))
  })
})
