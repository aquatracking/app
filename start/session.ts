/*
|--------------------------------------------------------------------------
| Session macros
|--------------------------------------------------------------------------
|
| "session.notify" flashes the notification shown once after a redirect
| (success or business error), shared with the pages by the Inertia
| middleware. "session.showLink" flashes the one-time link generated by an
| administrator (invitation, password reset), shown once in a window.
|
*/

import { Session } from '@adonisjs/session'
import type { GeneratedLink, Notification } from '#middleware/inertia_middleware'

declare module '@adonisjs/session' {
  interface Session {
    notify(type: Notification['type'], message: string): void
    showLink(link: GeneratedLink): void
  }
}

Session.macro('notify', function (this: Session, type: Notification['type'], message: string) {
  const notification: Notification = { type, message }
  this.flash('notification', notification)
})

Session.macro('showLink', function (this: Session, link: GeneratedLink) {
  this.flash('generatedLink', link)
})
